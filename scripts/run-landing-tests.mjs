import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { join } from "node:path"

const read = path => readFileSync(join(process.cwd(), path), "utf8")
const page = read("src/pages/PublicHomePage.jsx")
const styles = read("src/styles/landing-clean.css")
const header = read("src/components/landing/LandingHeader.jsx")
const content = read("src/components/landing/landingContent.js")
const main = read("src/main.jsx")
const index = read("index.html")

// Une seule page éditoriale : pas de mockup de téléphone ou de capture dans le rendu.
assert.equal([...page.matchAll(/<h1\b/g)].length, 1, "single H1 required")
assert.match(page, /className="landing-page bk-landing"/, "clean landing root missing")
assert.match(page, /landing-clean\.css/, "clean visual layer not imported")
assert.doesNotMatch(page, /HeroProductDemo|ProductPhoneMockup|LANDING_REFERENCE_IMAGES|AdvisorAndLocalDeals|LandingPillar|<img\b/, "no smartphone or screenshot components may be rendered")
assert.doesNotMatch(page, /drapeau-reunionnais\.png|heroPhone|advisorPhone/, "legacy landing decorative assets must not return")
assert.match(page, /id="landing-title"/, "hero must remain accessible")
assert.match(page, /id="fonctionnalites"/, "features anchor missing")
assert.match(page, /id="conseiller"/, "advisor anchor missing")
assert.match(page, /id="bons-plans"/, "deals anchor missing")
assert.match(page, /id="je-propose"/, "future professional section anchor missing")
assert.match(page, /href=\{appHref\}/, "CTA must work for both authenticated and guest visitors")
assert.match(page, /href="#fonctionnalites"/, "secondary CTA must work")
assert.match(page, /12 mois de visibilité offerts au lancement/, "public opening offer not presented")
assert.match(page, /dans la limite des places disponibles/, "offer must describe limits without publishing quota")
assert.doesNotMatch(page, /30 premières|30 fiches/, "opening quota must not be advertised")
assert.match(page, /Sans engagement, sans paiement et sans obligation de partenariat/, "transparency notice must be retained")
assert.match(page, /en préparation/, "do not imply professional self-service is already live")
assert.match(page, /contact\.budgetkazpei@gmail\.com/, "contact link missing")
assert.match(page, /href="\/mentions-legales"/, "legal link missing")

// Même parcours visible en français et créole, y compris l'espace professionnel.
assert.match(page, /const COPY = \{[\s\S]*fr:[\s\S]*kr:/, "two locale copies required")
assert.match(page, /Mi propoz/, "professional CTA must be localized")
assert.match(page, /Out kotidien pli sinp/, "Creole hero missing")
assert.match(page, /Nou lé an train prépar/, "Creole professional description missing")
assert.match(page, /LANDING_LANGUAGE_STORAGE_KEY/, "language preference persistence missing")
assert.match(page, /useLandingSeo\(content\.seo, language\)/, "SEO must follow language")
assert.match(header, /aria-expanded=\{isMenuOpen\}/, "mobile navigation must expose state")
assert.match(header, /key === "Escape"/, "mobile menu must be dismissible")
assert.match(content, /localOffers/, "existing local deals editorial content must remain available")

// Ligne graphique conforme : fonds neutres, boutons clairs, contrastes et responsive.
assert.match(styles, /color-scheme:\s*light/, "landing must stay light")
assert.match(styles, /overflow-x:\s*clip/, "prevent horizontal overflow")
assert.match(styles, /@media \(max-width: 1024px\)/, "tablet layout missing")
assert.match(styles, /@media \(max-width: 640px\)/, "mobile layout missing")
assert.match(styles, /@media \(max-width: 370px\)/, "small Android layout missing")
assert.match(styles, /prefers-reduced-motion: reduce/, "reduced motion support missing")
assert.match(styles, /safe-area-inset-top/, "mobile safe area missing")
assert.match(styles, /min-height:\s*48px/, "touch-target rule missing")
assert.doesNotMatch(styles, /#(?:ea580c|c2410c|ff7012|ff7[0-9a-f]{4})\b/i, "orange is prohibited in landing")
assert.doesNotMatch(styles, /box-shadow|drop-shadow|linear-gradient|radial-gradient|rotateY|perspective:/i, "clean design must not use phone or decorative effects")
assert.doesNotMatch(styles, /background:\s*#(?:142033|152a4d|1[0-9a-f]{5})\b/i, "no dark button backgrounds")
assert.match(main, /isPublicLandingPath/, "public light-theme initialization must remain")
assert.match(index, /BudgetKazPéi — Budget, courses, aides et bons plans à La Réunion/, "SEO fallback missing")


// Cohérence graphique et fonctionnelle des deux pages publiques.
const offerPage = read("src/pages/PremiumLandingPage.jsx")
const offerCss = read("src/styles/landing-offers.css")
assert.match(offerPage, /landing-clean\.css/, "offer page must share the clean landing design")
assert.match(offerPage, /landing-offers\.css/, "offer-specific styles missing")
assert.match(offerPage, /bk-landing bk-offers-page/, "offer page must use shared visual root")
assert.doesNotMatch(offerPage, /import "\.\.\/styles\/landing\.css"/, "old reflective offer theme must not be loaded")
assert.match(offerPage, /premium-plan__billing-selector/, "monthly and yearly options must remain accessible")
assert.match(offerPage, /aria-pressed=\{billingPeriod === term\.id\}/, "billing selection state missing")
assert.match(offerPage, /4,99 €/, "monthly offer price must be preserved")
assert.match(offerPage, /49,90 €/, "yearly offer price must be preserved")
assert.match(offerPage, /STRIPE_LINKS\.premiumMonthly/, "monthly checkout link must be preserved")
assert.match(offerPage, /STRIPE_LINKS\.premiumAnnual/, "yearly checkout link must be preserved")
assert.match(offerPage, /href=\{href\}/, "free and premium CTAs must remain navigable")
assert.match(offerPage, /content\.faq\.items\.map/, "offer FAQ must remain available")
assert.match(offerPage, /const fr = language !== LANDING_LANGUAGES\.kr/, "offer translation must remain functional")
assert.doesNotMatch(offerPage, /<img\b|ProductPhoneMockup|HeroProductDemo/, "offer page must not show a phone or screenshot")
for (const cssSource of [styles, offerCss]) {
  assert.doesNotMatch(cssSource, /#(?:ea580c|c2410c|ff7012|fb923c)\b/i, "no orange in the visual identity")
  assert.doesNotMatch(cssSource, /linear-gradient\(|radial-gradient\(/, "no colored reflections or gradients")
  assert.doesNotMatch(cssSource, /filter:\s*drop-shadow|box-shadow:\s*0\s+\d+px/i, "no ornamental shadows")
  assert.match(cssSource, /@media \(max-width: 640px\)/, "mobile layout missing")
  assert.match(cssSource, /@media \(max-width: 370px\)/, "narrow Android layout missing")
}
assert.match(offerCss, /grid-template-columns: repeat\(2, minmax\(0, 1fr\)\)/, "desktop offer columns missing")
assert.match(offerCss, /grid-template-columns: 1fr/, "mobile offer stacking missing")
assert.match(offerCss, /font-size: clamp\(3\.1rem, 6\.1vw, 5\.9rem\)/, "large editorial hero heading missing")
assert.match(offerCss, /min-height:\s*45px/, "billing touch targets must be large enough")
assert.match(offerCss, /min-height:\s*51px/, "offer CTA touch target must be large enough")
assert.match(styles, /font-size: clamp\(2\.5rem, 4\.9vw, 4\.65rem\)/, "landing section headings must be increased")

console.log("Landing et offres épurées — tests passed.")
