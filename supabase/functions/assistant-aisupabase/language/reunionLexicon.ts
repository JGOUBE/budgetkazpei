export function normalizeReunionText(value = "") {
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/['’]/g, " ")
    .replace(/[^a-z0-9\s-]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

export function getExpressionsByIntent(intent: ReunionLexiconIntent): string[] {
  return REUNION_LEXICON
    .filter(entry => entry.intent === intent)
    .flatMap(entry => entry.expressions)
}

export function getExpressionsByCategory(category: ReunionLexiconCategory): string[] {
  return REUNION_LEXICON
    .filter(entry => entry.category === category)
    .flatMap(entry => entry.expressions)
}

export function textMatchesIntent(text: string, intent: ReunionLexiconIntent): boolean {
  const normalizedText = normalizeReunionText(text)
  return getExpressionsByIntent(intent).some(expression =>
    normalizedText.includes(normalizeReunionText(expression))
  )
}

export function findReunionIntents(text: string): ReunionLexiconIntent[] {
  const normalizedText = normalizeReunionText(text)

  return Array.from(
    new Set(
      REUNION_LEXICON
        .filter(entry =>
          entry.expressions.some(expression =>
            normalizedText.includes(normalizeReunionText(expression))
          )
        )
        .map(entry => entry.intent)
    )
  )
}

export function findReunionCategories(text: string): ReunionLexiconCategory[] {
  const intents = findReunionIntents(text)

  return Array.from(
    new Set(
      REUNION_LEXICON
        .filter(entry => intents.includes(entry.intent))
        .map(entry => entry.category)
    )
  )
}